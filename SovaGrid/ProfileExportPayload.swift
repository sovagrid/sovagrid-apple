// Dedicated large-backup import; ordinary WebKit file uploads keep their 4MiB cap.
enum PanelRestoreContract {
    static let fileBytes: Int64 = 8 * 1024 * 1024 * 1024
    static let totalBytes: Int64 = 16 * 1024 * 1024 * 1024
    static let readBytes = 262_144
    static let copyMessage = "Выберите до пяти обычных файлов копии. Если хранилище не поддерживает чтение по частям, скопируйте их в «На устройстве» и выберите снова."
    static func replyJSON(_ value: [String: Any]) -> String? {
        guard let raw = try? JSONSerialization.data(withJSONObject: value, options: [.withoutEscapingSlashes]),
              raw.count <= 400_000 else { return nil }
        return String(data: raw, encoding: .utf8)
    }
    static func token(_ value: String, count: Int) -> Bool {
        value.utf8.count == count && value.utf8.allSatisfy { (48...57).contains($0) || (97...102).contains($0) }
    }
    static func validRange(size: Int64, offset: Int64, length: Int) -> Bool {
        size > 0 && size <= fileBytes && offset >= 0 && offset <= size && length > 0
            && length <= readBytes && Int64(length) <= size - offset
    }
}

struct PanelRestoreMessage {
    let action: String
    let session: String
    let id: String
    let handle: String?
    let offset: Int64?
    let length: Int?
    static func parse(_ body: Any) -> PanelRestoreMessage? {
        guard let text = body as? String, text.utf8.count <= 4096,
              let raw = text.data(using: .utf8),
              let object = (try? JSONSerialization.jsonObject(with: raw)) as? [String: Any],
              let action = object["action"] as? String,
              let session = object["session"] as? String, PanelRestoreContract.token(session, count: 32),
              let id = object["id"] as? String, PanelRestoreContract.token(id, count: 32) else { return nil }
        let expected: Set<String>
        if action == "read" { expected = ["action", "session", "id", "handle", "offset", "length"] }
        else if action == "pick" || action == "release" { expected = ["action", "session", "id"] }
        else { return nil }
        guard Set(object.keys) == expected else { return nil }
        if action != "read" { return Self(action: action, session: session, id: id, handle: nil, offset: nil, length: nil) }
        guard let handle = object["handle"] as? String, PanelRestoreContract.token(handle, count: 64),
              let offset = PanelDownloadContract.integer(object["offset"]), offset <= PanelRestoreContract.fileBytes,
              let length = PanelDownloadContract.integer(object["length"]),
              length > 0, length <= PanelRestoreContract.readBytes else { return nil }
        return Self(action: action, session: session, id: id, handle: handle, offset: offset, length: Int(length))
    }
}

final class PanelRestoreFiles {
    private final class Entry {
        let source: URL
        let scoped: Bool
        let name: String
        let size: Int64
        let proof: [String]
        private var descriptor: Int32
        private let lock = NSLock()
        init(_ source: URL) throws {
            guard source.isFileURL, PanelDownloadContract.safeFilename(source.lastPathComponent) else {
                throw CocoaError(.fileReadInvalidFileName)
            }
            let scoped = source.startAccessingSecurityScopedResource()
            let fd = Darwin.open(source.path, O_RDONLY | O_NOFOLLOW | O_CLOEXEC | O_NONBLOCK)
            guard fd >= 0 else {
                if scoped { source.stopAccessingSecurityScopedResource() }
                throw CocoaError(.fileReadNoPermission)
            }
            do {
                let proof = try PanelRestoreFiles.fingerprint(fd)
                guard Darwin.lseek(fd, 0, SEEK_CUR) >= 0, let size = Int64(proof[2]) else {
                    throw CocoaError(.fileReadUnknown)
                }
                self.source = source; self.scoped = scoped; self.descriptor = fd
                self.proof = proof; self.size = size; self.name = source.lastPathComponent
            } catch {
                Darwin.close(fd)
                if scoped { source.stopAccessingSecurityScopedResource() }
                throw error
            }
        }
        func duplicate() throws -> Int32 {
            lock.lock(); defer { lock.unlock() }
            guard descriptor >= 0 else { throw CocoaError(.fileReadUnknown) }
            let fd = Darwin.fcntl(descriptor, F_DUPFD_CLOEXEC, 0)
            guard fd >= 0 else { throw CocoaError(.fileReadUnknown) }
            return fd
        }
        func close() {
            lock.lock(); defer { lock.unlock() }
            if descriptor >= 0 {
                Darwin.close(descriptor); descriptor = -1
                if scoped { source.stopAccessingSecurityScopedResource() }
            }
        }
        deinit { close() }
    }
    private let lock = NSLock()
    private var entries: [String: Entry] = [:]
    private var closed = false
    private static func fingerprint(_ fd: Int32) throws -> [String] {
        var info = stat()
        guard Darwin.fstat(fd, &info) == 0, (info.st_mode & S_IFMT) == S_IFREG,
              info.st_nlink > 0, info.st_size > 0, info.st_size <= PanelRestoreContract.fileBytes else {
            throw CocoaError(.fileReadUnknown)
        }
        return [String(info.st_dev), String(info.st_ino), String(info.st_size), String(info.st_mode),
                String(info.st_nlink), String(info.st_uid), String(info.st_gid),
                String(info.st_mtimespec.tv_sec), String(info.st_mtimespec.tv_nsec),
                String(info.st_ctimespec.tv_sec), String(info.st_ctimespec.tv_nsec)]
    }
    func add(_ url: URL) throws -> [String: Any] {
        let entry = try Entry(url)
        lock.lock(); defer { lock.unlock() }
        guard !closed, entries.count < 5,
              entry.size <= PanelRestoreContract.totalBytes - entries.values.reduce(0, { $0 + $1.size }) else {
            entry.close(); throw CocoaError(.fileReadTooLarge)
        }
        let handle = (UUID().uuidString + UUID().uuidString).lowercased().replacingOccurrences(of: "-", with: "")
        guard entries[handle] == nil else { entry.close(); throw CocoaError(.fileReadUnknown) }
        entries[handle] = entry
        return ["handle": handle, "name": entry.name, "size": entry.size]
    }
    func read(handle: String, offset: Int64, length: Int) throws -> Data {
        lock.lock()
        guard let entry = entries[handle], PanelRestoreContract.validRange(size: entry.size, offset: offset, length: length) else {
            lock.unlock(); throw CocoaError(.fileReadUnknown)
        }
        let fd: Int32
        do { fd = try entry.duplicate() } catch { lock.unlock(); throw error }
        lock.unlock()
        defer { Darwin.close(fd) }
        guard try Self.fingerprint(fd) == entry.proof else { throw CocoaError(.fileReadUnknown) }
        var data = Data(count: length)
        try data.withUnsafeMutableBytes { (buffer: UnsafeMutableRawBufferPointer) in
            var count = 0
            while count < length {
                let n = Darwin.pread(fd, buffer.baseAddress!.advanced(by: count), length - count, off_t(offset + Int64(count)))
                if n < 0 && errno == EINTR { continue }
                guard n > 0 else { throw CocoaError(.fileReadUnknown) }
                count += n
            }
        }
        guard try Self.fingerprint(fd) == entry.proof else { throw CocoaError(.fileReadUnknown) }
        lock.lock(); defer { lock.unlock() }
        guard entries[handle] === entry, !closed else { throw CocoaError(.fileReadUnknown) }
        return data
    }
    func close() {
        lock.lock(); closed = true
        let owned = Array(entries.values); entries.removeAll()
        lock.unlock()
        owned.forEach { $0.close() }
    }
    deinit { close() }
}

