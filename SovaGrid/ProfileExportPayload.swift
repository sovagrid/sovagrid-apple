/// Plaintext arrives only after the Web panel has decrypted the sealed VPN profile.
/// Keep this parser separate from WebKit so its bounds and canonical encoding can be tested.
struct ProfileExportPayload {
    let filename: String
    let data: Data

    private static let filenamePattern = try! NSRegularExpression(
        pattern: #"\A[a-z][a-z0-9-]{1,31}-[a-z][a-z0-9_-]{0,31}\.conf\z"#
    )

    static func parse(_ body: Any) -> ProfileExportPayload? {
        guard let text = body as? String,
              text.utf8.count <= 23_000,
              let source = text.data(using: .utf8),
              let value = try? JSONSerialization.jsonObject(with: source),
              let object = value as? [String: Any],
              Set(object.keys) == Set(["version", "filename", "data"]),
              let version = object["version"] as? NSNumber,
              CFGetTypeID(version) != CFBooleanGetTypeID(),
              version.stringValue == "1",
              let filename = object["filename"] as? String,
              filenamePattern.firstMatch(in: filename, range: NSRange(filename.startIndex..., in: filename))?.range
                  == NSRange(filename.startIndex..., in: filename),
              let encoded = object["data"] as? String,
              !encoded.isEmpty,
              encoded.utf8.count <= 21_846,
              encoded.utf8.allSatisfy({ byte in
                  (65...90).contains(byte) || (97...122).contains(byte)
                      || (48...57).contains(byte) || byte == 45 || byte == 95
              }) else { return nil }

        let padded = encoded.replacingOccurrences(of: "-", with: "+")
            .replacingOccurrences(of: "_", with: "/")
            .padding(toLength: ((encoded.count + 3) / 4) * 4, withPad: "=", startingAt: 0)
        guard let data = Data(base64Encoded: padded),
              (1...16_384).contains(data.count),
              data.base64EncodedString().replacingOccurrences(of: "+", with: "-")
                  .replacingOccurrences(of: "/", with: "_")
                  .replacingOccurrences(of: "=", with: "") == encoded else { return nil }
        return ProfileExportPayload(filename: filename, data: data)
    }
}

enum ProfileExportTemporaryFiles {
    private static let prefix = "sovagrid-profile-"

    static func directory(for id: UUID) -> URL {
        FileManager.default.temporaryDirectory
            .appendingPathComponent(prefix + id.uuidString, isDirectory: true)
    }

    /// Also covers an abrupt app termination, when dismissal callbacks cannot run.
    static func removeStaleAtLaunch() {
        let manager = FileManager.default
        guard let entries = try? manager.contentsOfDirectory(at: manager.temporaryDirectory,
                                                               includingPropertiesForKeys: [.isDirectoryKey,
                                                                                            .isSymbolicLinkKey]) else { return }
        for entry in entries {
            let name = entry.lastPathComponent
            let matchingPrefix = [prefix, "sovagrid-download-", "sovagrid-upload-"].first {
                name.hasPrefix($0) && UUID(uuidString: String(name.dropFirst($0.count))) != nil
            }
            guard matchingPrefix != nil,
                  let properties = try? entry.resourceValues(forKeys: [.isDirectoryKey, .isSymbolicLinkKey]),
                  properties.isDirectory == true, properties.isSymbolicLink != true else { continue }
            try? manager.removeItem(at: entry)
        }
    }
}

/// Bounded streaming bridge for files generated by the authenticated local panel.
/// File bytes never leave the SSH tunnel or enter a public URL/clipboard.
enum PanelDownloadContract {
    static let maximumBytes: Int64 = 32 * 1024 * 1024 * 1024
    static let maximumChunkBytes = 65_536

    static func safeFilename(_ value: String) -> Bool {
        !value.isEmpty && value != "." && value != ".." && value.utf8.count <= 240
            && value == value.trimmingCharacters(in: .whitespacesAndNewlines)
            && value.rangeOfCharacter(from: .controlCharacters) == nil
            && !value.contains("/") && !value.contains("\\") && !value.contains(":")
    }

    static func integer(_ value: Any?) -> Int64? {
        guard let number = value as? NSNumber, CFGetTypeID(number) != CFBooleanGetTypeID(),
              let integer = Int64(number.stringValue), integer >= 0,
              integer <= maximumBytes else { return nil }
        return integer
    }
}

struct PanelDownloadMessage {
    let operation: String
    let id: String
    let filename: String?
    let index: Int64?
    let data: Data?
    let bytes: Int64?

    static func parse(_ body: Any) -> PanelDownloadMessage? {
        guard let raw = body as? String, raw.utf8.count <= 90_000,
              let encoded = raw.data(using: .utf8),
              let value = try? JSONSerialization.jsonObject(with: encoded) as? [String: Any],
              let operation = value["op"] as? String, let id = value["id"] as? String,
              id.count == 32, id.utf8.allSatisfy({ (48...57).contains($0) || (97...102).contains($0) })
        else { return nil }
        var filename: String?, index: Int64?, data: Data?, bytes: Int64?
        let keys: Set<String>
        switch operation {
        case "start":
            keys = ["op", "id", "filename"]
            guard let name = value["filename"] as? String, PanelDownloadContract.safeFilename(name) else { return nil }
            filename = name
        case "metadata":
            keys = ["op", "id", "bytes"]
            if !(value["bytes"] is NSNull) {
                guard let count = PanelDownloadContract.integer(value["bytes"]) else { return nil }
                bytes = count
            }
        case "chunk":
            keys = ["op", "id", "index", "data"]
            guard let number = PanelDownloadContract.integer(value["index"]),
                  let base64 = value["data"] as? String, base64.utf8.count <= 87_384,
                  let decoded = Data(base64Encoded: base64),
                  (1...PanelDownloadContract.maximumChunkBytes).contains(decoded.count),
                  decoded.base64EncodedString() == base64 else { return nil }
            index = number; data = decoded
        case "complete":
            keys = ["op", "id", "bytes"]
            guard let number = PanelDownloadContract.integer(value["bytes"]) else { return nil }
            bytes = number
        case "cancel": keys = ["op", "id"]
        default: return nil
        }
        guard Set(value.keys) == keys else { return nil }
        return Self(operation: operation, id: id, filename: filename, index: index, data: data, bytes: bytes)
    }

    var step: String { operation == "chunk" ? String(index ?? -1) : operation }
}

final class PanelDownloadSession {
    let id: String
    let filename: String
    let directory: URL
    let file: URL
    private var handle: FileHandle?
    private var metadataReceived = false
    private var expectedBytes: Int64?
    private var index: Int64 = 0
    private(set) var receivedBytes: Int64 = 0
    private(set) var complete = false
    private let limit: Int64

    init(id: String, filename: String, base: URL = FileManager.default.temporaryDirectory,
         limit: Int64 = PanelDownloadContract.maximumBytes) throws {
        guard PanelDownloadContract.safeFilename(filename) else { throw CocoaError(.fileWriteInvalidFileName) }
        self.id = id; self.filename = filename; self.limit = limit
        directory = base.appendingPathComponent("sovagrid-download-" + UUID().uuidString, isDirectory: true)
        file = directory.appendingPathComponent(filename, isDirectory: false)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: false,
                                                attributes: [.posixPermissions: 0o700])
        var attributes: [FileAttributeKey: Any] = [.posixPermissions: 0o600]
#if os(iOS)
        attributes[.protectionKey] = FileProtectionType.complete
#endif
        guard FileManager.default.createFile(atPath: file.path, contents: nil, attributes: attributes) else {
            try? FileManager.default.removeItem(at: directory)
            throw CocoaError(.fileWriteUnknown)
        }
        do { handle = try FileHandle(forWritingTo: file) }
        catch { try? FileManager.default.removeItem(at: directory); throw error }
    }

    func accept(_ message: PanelDownloadMessage) throws {
        guard message.id == id, !complete, let handle else { throw CocoaError(.fileWriteUnknown) }
        switch message.operation {
        case "metadata":
            guard !metadataReceived, message.bytes.map({ $0 <= limit }) ?? true else { throw CocoaError(.fileWriteOutOfSpace) }
            metadataReceived = true; expectedBytes = message.bytes
        case "chunk":
            guard metadataReceived, message.index == index, let data = message.data,
                  Int64(data.count) <= limit - receivedBytes,
                  expectedBytes.map({ receivedBytes + Int64(data.count) <= $0 }) ?? true
            else { throw CocoaError(.fileWriteUnknown) }
            try handle.write(contentsOf: data)
            receivedBytes += Int64(data.count); index += 1
        case "complete":
            guard metadataReceived, message.bytes == receivedBytes,
                  expectedBytes.map({ $0 == receivedBytes }) ?? true else { throw CocoaError(.fileWriteUnknown) }
            try handle.synchronize(); try handle.close(); self.handle = nil; complete = true
        default: throw CocoaError(.fileWriteUnknown)
        }
    }

    func discard() {
        try? handle?.close(); handle = nil
        try? FileManager.default.removeItem(at: directory)
    }

    deinit { discard() }
}

/// Keep one bounded private upload snapshot while WebKit uses the selected file.
final class PanelUploadFile {
    static let maximumBytes = 4 * 1024 * 1024
    let directory: URL
    let file: URL

    init(source: URL, base: URL = FileManager.default.temporaryDirectory) throws {
        guard source.isFileURL, PanelDownloadContract.safeFilename(source.lastPathComponent) else {
            throw CocoaError(.fileReadInvalidFileName)
        }
        let scoped = source.startAccessingSecurityScopedResource()
        defer { if scoped { source.stopAccessingSecurityScopedResource() } }
        let values = try source.resourceValues(forKeys: [.isRegularFileKey, .isSymbolicLinkKey, .fileSizeKey])
        guard values.isRegularFile == true, values.isSymbolicLink != true,
              let size = values.fileSize, size <= Self.maximumBytes else { throw CocoaError(.fileReadTooLarge) }
        directory = base.appendingPathComponent("sovagrid-upload-" + UUID().uuidString, isDirectory: true)
        file = directory.appendingPathComponent(source.lastPathComponent)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: false,
                                                attributes: [.posixPermissions: 0o700])
        do {
            // Read at most the promised ceiling even if the source changes after stat().
            let input = try FileHandle(forReadingFrom: source)
            defer { try? input.close() }
            var data = Data()
            while let chunk = try input.read(upToCount: min(65_536, Self.maximumBytes + 1 - data.count)), !chunk.isEmpty {
                data.append(chunk)
                if data.count > Self.maximumBytes { break }
            }
            guard data.count <= Self.maximumBytes, data.count == size else { throw CocoaError(.fileReadTooLarge) }
#if os(iOS)
            try data.write(to: file, options: [.atomic, .completeFileProtection])
#else
            try data.write(to: file, options: [.atomic])
#endif
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
        } catch { try? FileManager.default.removeItem(at: directory); throw error }
    }

    deinit { try? FileManager.default.removeItem(at: directory) }
}


